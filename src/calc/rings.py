"""Bounded exact arithmetic and ideals in finite residue rings ``Z/nZ``.

Only commutative integer residue rings with ``2 <= n <= 4096`` are modeled.
The zero ring ``Z/1Z`` can occur as a *quotient* but is not itself accepted as
an ambient ``ResidueRing``. This module is not a general abstract-ring engine.
"""

from __future__ import annotations

from dataclasses import dataclass
from math import gcd, lcm
from collections.abc import Iterable
from itertools import islice


_MAX_MODULUS = 4096
_MAX_GENERATORS = 128
_MAX_CRT_CONGRUENCES = 16
_MAX_CRT_PRODUCT = 2**63 - 1
_MAX_EXPONENT = 1_000_000


def _integer(value: object, name: str) -> int:
    if type(value) is not int:
        raise TypeError(f"{name} must be an integer (bool is not accepted)")
    return value


def _modulus(value: object) -> int:
    n = _integer(value, "modulus")
    if not 2 <= n <= _MAX_MODULUS:
        raise ValueError(f"modulus must be between 2 and {_MAX_MODULUS}")
    return n


@dataclass(frozen=True, slots=True)
class ResidueRing:
    """Commutative ring ``Z/nZ`` represented by canonical integer residues.

    Every operation accepts arbitrary Python integers and returns a residue
    in ``range(n)``. Floats, booleans, and implicit coercion are rejected.
    """

    modulus: int

    def __post_init__(self) -> None:
        _modulus(self.modulus)

    def normalize(self, value: int) -> int:
        return _integer(value, "ring element") % self.modulus

    def add(self, left: int, right: int) -> int:
        return (self.normalize(left) + self.normalize(right)) % self.modulus

    def neg(self, value: int) -> int:
        return (-self.normalize(value)) % self.modulus

    def subtract(self, left: int, right: int) -> int:
        return self.add(left, self.neg(right))

    def multiply(self, left: int, right: int) -> int:
        return self.normalize(left) * self.normalize(right) % self.modulus

    def power(self, value: int, exponent: int) -> int:
        k = _integer(exponent, "exponent")
        if not 0 <= k <= _MAX_EXPONENT:
            raise ValueError("exponent is outside the supported nonnegative budget")
        return pow(self.normalize(value), k, self.modulus)

    def is_unit(self, value: int) -> bool:
        return gcd(self.normalize(value), self.modulus) == 1

    def inverse(self, value: int) -> int:
        a = self.normalize(value)
        if gcd(a, self.modulus) != 1:
            raise ZeroDivisionError("nonunit has no multiplicative inverse")
        return pow(a, -1, self.modulus)

    def is_zero_divisor(self, value: int) -> bool:
        """Use the conventional nonzero zero-divisor definition."""
        a = self.normalize(value)
        return a != 0 and gcd(a, self.modulus) > 1

    def units(self) -> tuple[int, ...]:
        return tuple(a for a in range(self.modulus) if self.is_unit(a))

    def ideal(self, *generators: int) -> PrincipalIdeal:
        """Ideal ``(a1,...,ak)``; the empty list generates the zero ideal.

        In ``Z/nZ`` this equals the principal ideal ``(gcd(n,a1,...,ak))``.
        """
        if len(generators) > _MAX_GENERATORS:
            raise ValueError("too many ideal generators")
        divisor = self.modulus
        for value in generators:
            divisor = gcd(divisor, self.normalize(value))
        return PrincipalIdeal(self, divisor)

    def annihilator(self, value: int) -> PrincipalIdeal:
        """Return ``Ann(a)={x:a*x=0}``, generated by ``n/gcd(n,a)``."""
        a = self.normalize(value)
        return self.ideal(self.modulus // gcd(self.modulus, a))


@dataclass(frozen=True, slots=True)
class PrincipalIdeal:
    """A canonical ideal of ``Z/nZ`` identified by its positive divisor of n.

    ``divisor=1`` is the whole ring, while ``divisor=n`` is the zero ideal.
    ``R/I`` has ``divisor`` residue classes even when that count is one.
    """

    ring: ResidueRing
    divisor: int

    def __post_init__(self) -> None:
        if not isinstance(self.ring, ResidueRing):
            raise TypeError("ring must be a ResidueRing")
        d = _integer(self.divisor, "ideal divisor")
        if d < 1 or self.ring.modulus % d != 0:
            raise ValueError("ideal divisor must be a positive divisor of modulus")

    @property
    def order(self) -> int:
        """Number of elements of this ideal."""
        return self.ring.modulus // self.divisor

    @property
    def quotient_order(self) -> int:
        """Number of elements of the quotient ring ``R/I``."""
        return self.divisor

    @property
    def generator(self) -> int:
        return self.divisor % self.ring.modulus

    def contains(self, value: int) -> bool:
        return self.ring.normalize(value) % self.divisor == 0

    def elements(self) -> tuple[int, ...]:
        return tuple(range(0, self.ring.modulus, self.divisor))

    def quotient_class(self, value: int) -> int:
        """Map an ambient residue to ``R/I ≅ Z/divisor Z``."""
        return self.ring.normalize(value) % self.divisor

    def quotient_add(self, left: int, right: int) -> int:
        return (self.quotient_class(left) + self.quotient_class(right)) % self.divisor

    def quotient_multiply(self, left: int, right: int) -> int:
        return self.quotient_class(left) * self.quotient_class(right) % self.divisor

    def _compatible(self, other: PrincipalIdeal) -> None:
        if not isinstance(other, PrincipalIdeal) or other.ring != self.ring:
            raise ValueError("ideal operations require the same ambient ring")

    def sum(self, other: PrincipalIdeal) -> PrincipalIdeal:
        """Ideal sum ``I+J`` corresponds to ``gcd(divisor_I,divisor_J)``."""
        self._compatible(other)
        return PrincipalIdeal(self.ring, gcd(self.divisor, other.divisor))

    def intersection(self, other: PrincipalIdeal) -> PrincipalIdeal:
        """Ideal intersection ``I∩J`` corresponds to the lcm of divisors."""
        self._compatible(other)
        return PrincipalIdeal(self.ring, lcm(self.divisor, other.divisor))

    def product(self, other: PrincipalIdeal) -> PrincipalIdeal:
        """Ideal product ``IJ`` is generated by ``divisor_I * divisor_J``."""
        self._compatible(other)
        return self.ring.ideal(self.divisor * other.divisor)


def chinese_remainder(
    residues: Iterable[int], moduli: Iterable[int],
) -> tuple[int, int]:
    """Solve pairwise-coprime congruences, returning ``(x, product_modulus)``.

    The unique canonical solution satisfies ``x % m_i = residues_i % m_i``.
    At most 16 congruences with moduli 2..4096 and product <2**63 are allowed.
    Empty input, inconsistent arity, and noncoprime moduli are rejected.
    """
    if isinstance(residues, (str, bytes)) or isinstance(moduli, (str, bytes)):
        raise TypeError("residues and moduli must be integer iterables")
    try:
        rr = tuple(islice(iter(residues), _MAX_CRT_CONGRUENCES + 1))
        mm = tuple(islice(iter(moduli), _MAX_CRT_CONGRUENCES + 1))
    except TypeError as exc:
        raise TypeError("residues and moduli must be iterable") from exc
    if not rr or len(rr) != len(mm):
        raise ValueError("CRT requires at least one residue per modulus")
    if len(rr) > _MAX_CRT_CONGRUENCES:
        raise ValueError("too many CRT congruences")
    x, product = 0, 1
    for residue, candidate_modulus in zip(rr, mm):
        a = _integer(residue, "residue")
        modulus = _modulus(candidate_modulus)
        if gcd(product, modulus) != 1:
            raise ValueError("CRT moduli must be pairwise coprime")
        if product > _MAX_CRT_PRODUCT // modulus:
            raise ValueError("CRT modulus product exceeds resource bound")
        adjustment = ((a - x) * pow(product, -1, modulus)) % modulus
        x += product * adjustment
        product *= modulus
    return x % product, product


__all__ = ["ResidueRing", "PrincipalIdeal", "chinese_remainder"]
